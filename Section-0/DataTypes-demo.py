# Example 1: Integer
a = 1

print("Value:", a)
print("Type:", type(a))

# Example 2: Float
print("Float Type:", type(1.5))

# Example 3: String
print("String Type:", type("1.5"))

# Example 4: Boolean
print("Boolean Type:", type(True))

# Example 5: String operations
value = "Value"

print("Uppercase:", value.upper())

# Example 6: Reassigning variables
value = 1
print("Integer:", type(value))

value = True
print("Boolean:", type(value))

value = [1, 2]
print("List:", type(value))

# Example 7: Length of a string
name = "Python"

print("Length:", len(name))